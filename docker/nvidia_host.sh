#!/usr/bin/env bash
# NVIDIA GPU in a container without the NVIDIA container runtime (shared host, no root): what the
# toolkit does, by hand. The devices and the user-space libraries of the running host driver go
# into the container, and EGL loads only the NVIDIA vendor (Ogre picks the EGL device itself, and
# Mesa cannot drive NVIDIA devices). Used by docker/aero.sh (GCS/Gazebo) and isaac/host.sh
# (aero-isaac container: NVENC for the video).
#
#   nvidia_host.sh available        exit 0 when this applies (NVIDIA driver, no NVIDIA runtime)
#   nvidia_host.sh compose <file>   writes a compose override for the service `aero`, prints <file>
#   nvidia_host.sh run-args         prints `docker run` arguments, one per line
set -euo pipefail
LIB=/usr/lib/x86_64-linux-gnu
VENDOR=/usr/share/glvnd/egl_vendor.d/10_nvidia.json

available() {
  [ -e /dev/nvidiactl ] && [ -r /proc/driver/nvidia/version ] &&
    ! docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q nvidia
}
version() { sed -n 's/.*Kernel Module  *\([0-9.]*\).*/\1/p' /proc/driver/nvidia/version; }
devices() {
  local f
  for f in /dev/nvidia[0-9]* /dev/nvidiactl /dev/nvidia-modeset /dev/nvidia-uvm /dev/nvidia-uvm-tools; do
    [ -e "$f" ] && echo "$f"
  done
}
mounts() {  # host:container pairs: versioned libraries, their sonames, the EGL vendor file
  local ver lib link f
  ver=$(version)
  [ -e "$VENDOR" ] && echo "$VENDOR:$VENDOR"
  for lib in "$LIB"/lib*nvidia*.so."$ver" "$LIB"/libcuda.so."$ver" "$LIB"/libnvcuvid.so."$ver"; do
    [ -e "$lib" ] && echo "$lib:$lib"
  done
  for link in "$LIB"/lib*nvidia*.so.[0-9] "$LIB"/libcuda.so.1 "$LIB"/libnvcuvid.so.1; do
    f=$(readlink -f "$link" 2>/dev/null) || continue
    [[ "$f" == *".so.$ver" ]] && echo "$f:$link"
  done
}
ENVS=("__EGL_VENDOR_LIBRARY_FILENAMES=$VENDOR" "__GLX_VENDOR_LIBRARY_NAME=nvidia" "NVIDIA_DRIVER_CAPABILITIES=all")

case "${1:-}" in
  available) available ;;
  compose)
    out="$2"; mkdir -p "$(dirname "$out")"
    {
      echo "# generated by docker/nvidia_host.sh for NVIDIA driver $(version)"
      echo "services:"
      echo "  aero:"
      echo "    devices: !override"
      devices | sed 's/.*/      - &:&/'
      echo "    environment:"
      for e in "${ENVS[@]}"; do echo "      ${e%%=*}: ${e#*=}"; done
      echo "    volumes:"
      mounts | sed 's/.*/      - &:ro/'
    } > "$out"
    echo "$out"
    ;;
  run-args)
    devices | sed 's/^/--device=/'
    for e in "${ENVS[@]}"; do echo "--env=$e"; done
    mounts | sed 's/^/--volume=/; s/$/:ro/'
    ;;
  *) sed -n '2,12p' "$0"; exit 1 ;;
esac
