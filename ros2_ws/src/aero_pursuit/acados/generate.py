#!/usr/bin/env python3
"""Generates (and optionally compiles) a pursuit MPC solver from pursuit_ocp.py.

    generate.py <out dir>                    build time (CMake, configure step): the default
                                             (N, DT) of pursuit_ocp.py as C sources that CMake
                                             compiles into libaero_pursuit_acados, plus
                                             pursuit_mpc_dims.hpp and acados_default_api.cpp
    generate.py <out dir> --N 40 --dt 0.05   run time (control/acados_variants.cpp): generates the
                                             (N, dt) variant and compiles it with the acados
                                             Makefile into <out dir>/<name>/libacados_ocp_solver_<name>.so;
                                             the last line printed is that path

Each variant has its own C prefix (pursuit_ocp.variant_name), so the node can hold several.
"""
import argparse
import shutil
import sys
from pathlib import Path

from acados_template import AcadosOcpSolver

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pursuit_ocp as P  # noqa: E402

DIMS = """// Generated by acados/generate.py from acados/pursuit_ocp.py. Do not edit.
#pragma once

namespace aero_pursuit::control::pursuit_mpc
{{
constexpr int N = {N};          // default horizon steps (the compiled-in variant)
constexpr double DT = {DT!r};   // default step [s]
constexpr int NX = {NX};        // state  [p_rel, v_rel, psi]
constexpr int NU = {NU};        // input  [a_chaser, r]
constexpr int NY = {NY};        // stage cost residuals [x; bearing (2); u]
constexpr int NY_E = {NY_E};    // terminal cost residuals [x; bearing (2)]
constexpr int NP = {NP};        // stage parameter: c = tan(usable half field of view)
constexpr int NH = {NH};        // field-of-view inequalities (stages 1..N)
constexpr double INFTY = {INFTY!r};  // acados "no bound"

// Initial weights / limits (defaults of the GCS mpc.params.* names)
constexpr double Q_P[3] = {{{Q_P}}};
constexpr double Q_V[3] = {{{Q_V}}};
constexpr double R_A[3] = {{{R_A}}};
constexpr double Q_F = {Q_F!r};
constexpr double A_MAX[3] = {{{A_MAX}}};
constexpr double Q_PSI = {Q_PSI!r};
constexpr double R_R = {R_R!r};
constexpr double R_MAX = {R_MAX!r};
constexpr double FOV_DEG = {FOV_DEG!r};
constexpr double FOV_MARGIN_DEG = {FOV_MARGIN_DEG!r};
constexpr double W_FOV = {W_FOV!r};
}}  // namespace aero_pursuit::control::pursuit_mpc
"""

# Function table of the compiled-in variant: the same AcadosApi the run-time variants fill with
# dlsym (control/acados_api.hpp). The lambdas only adapt the typed capsule pointer to void *.
DEFAULT_API = """// Generated by acados/generate.py. Do not edit.
#include "aero_pursuit/control/acados_api.hpp"

#include "{n}/acados_solver_{n}.h"

namespace aero_pursuit::control
{{

const AcadosApi & defaultAcadosApi()
{{
  using C = {n}_solver_capsule;
  static const AcadosApi api{{
    "{n}", {N}, {DT!r},
    []() -> void * {{return {n}_acados_create_capsule();}},
    [](void * c) {{return {n}_acados_create(static_cast<C *>(c));}},
    [](void * c) {{return {n}_acados_solve(static_cast<C *>(c));}},
    [](void * c) {{return {n}_acados_free(static_cast<C *>(c));}},
    [](void * c) {{return {n}_acados_free_capsule(static_cast<C *>(c));}},
    [](void * c) -> void * {{return {n}_acados_get_nlp_config(static_cast<C *>(c));}},
    [](void * c) -> void * {{return {n}_acados_get_nlp_dims(static_cast<C *>(c));}},
    [](void * c) -> void * {{return {n}_acados_get_nlp_in(static_cast<C *>(c));}},
    [](void * c) -> void * {{return {n}_acados_get_nlp_out(static_cast<C *>(c));}},
    [](void * c, int stage, double * p, int np) {{
      return {n}_acados_update_params(static_cast<C *>(c), stage, p, np);}},
  }};
  return api;
}}

}}  // namespace aero_pursuit::control
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--N", type=int, help="run-time variant: horizon steps")
    ap.add_argument("--dt", type=float, help="run-time variant: step [s]")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    runtime = a.N is not None or a.dt is not None
    n = a.N if a.N is not None else P.N
    dt = a.dt if a.dt is not None else P.DT
    name = P.variant_name(n, dt)

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    ocp = P.ocp(n, dt)
    ocp.code_gen_options.code_export_directory = str(out / name)
    AcadosOcpSolver.generate(ocp, verbose=False)
    print(f"acados: {name} (N={n}, dt={dt}, nx={P.NX}, nu={P.NU})", flush=True)

    if runtime:
        AcadosOcpSolver.build(str(out / name), verbose=False)   # make ocp_shared_lib
        lib = out / name / f"libacados_ocp_solver_{name}.so"
        if not lib.exists():
            sys.exit(f"acados: {lib} was not generated")
        print(lib)
        return

    (out / "pursuit_mpc_dims.hpp").write_text(
        DIMS.format(N=n, DT=dt, NX=P.NX, NU=P.NU, NY=P.NY, NY_E=P.NY_E, NP=P.NP, NH=P.NH,
                    INFTY=P.INFTY, Q_F=P.Q_F, Q_PSI=P.Q_PSI, R_R=P.R_R, R_MAX=P.R_MAX,
                    FOV_DEG=P.FOV_DEG, FOV_MARGIN_DEG=P.FOV_MARGIN_DEG, W_FOV=P.W_FOV,
                    **{k: ", ".join(repr(float(v)) for v in getattr(P, k))
                       for k in ("Q_P", "Q_V", "R_A", "A_MAX")}))
    (out / "acados_default_api.cpp").write_text(DEFAULT_API.format(n=name, N=n, DT=dt))


if __name__ == "__main__":
    main()
